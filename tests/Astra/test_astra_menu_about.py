"""UI-тест окна «О программе» Altami Studio на Astra Linux.

Парный тест к TC-92 для Windows: тот же сценарий, свои координаты.

Стартовое состояние — конечное состояние TC-87: приложение уже запущено,
лицензия активирована, на экране главное окно. Состояние тест НЕ готовит:
первым шагом он сверяет экран с эталоном стартового состояния и при
расхождении падает, ничего не нажимая (то же правило, что в TC-87).

Сценарий:

1. Помощь -> «О программе»: открывается окно «Altami Studio».
2. Проверяем, что открыта вкладка «О программе Altami Studio» (а не соседняя
   «Плагины устройств»).
3. Проверяем, что кнопка OK отрисована ЦЕЛИКОМ и не обрезана нижним краем
   окна. Это геометрическая проверка, а не сравнение с эталоном: эталон
   снимается с живой машины, поэтому дефект вёрстки просто попал бы в эталон
   и тест был бы вечно зелёным. Разбор кадра — в
   `src.widget_geometry.find_button_borders`, тот же, что у TC-92.
4. Нажимаем OK — окно закрывается, тест завершён.

Приложение НАМЕРЕННО остаётся открытым в конце — как в TC-84 и TC-87: на нём
строятся следующие сценарии.

Имя файла и порядок в прогоне. Тесты с маркером `app` идут в конце прогона, а
между собой — в порядке сбора, то есть по алфавиту имён файлов (сортировка в
tests/conftest.py стабильна). «menu_about» стоит после «license_activation»,
поэтому цепочка складывается правильно: запуск (TC-84) -> активация лицензии
(TC-87) -> это окно. Переименование файла порядок сломает.

ЧЕМ ЭТОТ ТЕСТ ОТЛИЧАЕТСЯ ОТ TC-92 ПО РЕЗУЛЬТАТУ. На Windows кнопка OK
обрезана и TC-92 падает; здесь, по лицензии, кнопка целая — тест зелёный.
Причина видна на замерах живых ВМ 10.08.2026: окно «О программе» одной и той
же фиксированной высоты, а помещается в него разное число строк. На Astra по
лицензии их четыре (версия, пустая, копирайт, ссылка) — рамки кнопки на
y=596 и y=620, высота 25 px, ниже ещё 5 px фона до края окна. В демо-режиме
добавляется пятая строка «Демонстрационная версия.», всё съезжает вниз на
6 px, и нижняя рамка кнопки уходит за край окна — кнопка обрезана ровно так
же, как на Windows, где строк тоже пять (там две ссылки вместо одной).

То есть проверка не «всегда падает» и не «всегда зелёная»: она реагирует
на состав окна. Если тест позеленел на Windows или покраснел здесь — это
изменение вёрстки, а не сбой проверки.

ЭТАЛОНЫ СНИМАТЬ ТОЛЬКО С УСТОЯВШЕГОСЯ ОКНА. Если эталона нет, он создаётся
из первого же снятого кадра (правило бутстрапа, см. screenshot_compare), а
цикл ожидания успевает поймать окно ещё не дорисованным. Такой эталон потом
не совпадает ни с одним нормальным кадром. Поэтому, если эталоны удалили,
создавать их надо с ЗАВЕДОМО устоявшегося кадра: открыть окно руками,
выждать пару секунд и вырезать области.

Координаты и области сняты на живой ВМ 10.08.2026 в видеорежиме рабочего
стола 1920x1200, в лицензированном состоянии.
"""

import asyncio
import logging
from typing import Optional

import pytest
from PIL import Image

from src.widget_geometry import find_button_borders
from tests.base_tests import BaseVMTest

logger = logging.getLogger(__name__)

# --- Координаты кликов (пиксели гостя, режим рабочего стола 1920x1200) -------
HELP_MENU = (546, 40)       # пункт «Помощь» в строке меню главного окна
ABOUT_ITEM = (586, 171)     # «О программе» — последний пункт меню «Помощь»
OK_BUTTON = (1082, 608)     # середина кнопки OK окна «О программе»
MOUSE_PARK = (1750, 250)    # нейтральная точка: увести курсор из кадра

# --- Области для сравнения с эталоном (left, top, right, bottom) -------------
# Заголовок окна «Altami Studio»: значок и подпись белым по красной строке
# заголовка fly. Доказывает, что окно открылось, и по нему же видно, что оно
# закрылось после OK. Надпись одна и та же и в демо, и по лицензии — «Демо
# версия» дописывается только к заголовку ГЛАВНОГО окна.
ABOUT_TITLE_BOX = (781, 420, 890, 442)
# Обе вкладки целиком. Область захватывает и активную «О программе Altami
# Studio», и неактивную «Плагины устройств»: активная нарисована белой и
# приподнятой, неактивная — серой, поэтому эталон фиксирует не только надписи,
# но и то, КАКАЯ вкладка выбрана.
ABOUT_TABS_BOX = (782, 450, 1100, 484)
# Панель инструментов главного окна — по ней сверяется стартовое состояние.
# Та же область, что в TC-84 и TC-87.
APP_TOOLBAR_BOX = (0, 54, 1132, 96)

# --- Область разбора кнопки OK -----------------------------------------------
# Кроп для геометрической проверки: кнопка (рамки на y=596 и y=620, x от 1044
# до 1121) плюс запас вниз за нижний край окна (клиентская область кончается
# на y=625, дальше красная рамка fly). Запас нужен, чтобы кнопка попадала в
# кадр и при съезде вёрстки вниз — например в демо-режиме, где она съезжает на
# 6 px. По горизонтали кроп доведён ровно до правой границы страницы вкладок
# (x=1122): так линии во всю ширину окна занимают весь кроп и уверенно
# отличаются от рамки кнопки, которая заметно короче.
OK_BUTTON_BOX = (1010, 585, 1123, 660)

# --- Допуск на смещение окна -------------------------------------------------
# Дочерние окна на Astra встают от запуска к запуску с точностью до пары
# пикселей, и полоса титула высотой 20 px даёт от такого сдвига SSIM 0.46 при
# том же самом окне на экране. Та же причина и то же значение, что в TC-87.
# Главное окно развёрнуто и не смещается — его области допуска не требуют.
DIALOG_SHIFT = 2

# --- Таймауты опроса (секунды) -----------------------------------------------
DIALOG_TIMEOUT = 8.0      # появление окна «О программе» после клика по пункту
DISMISS_TIMEOUT = 6.0     # исчезновение окна после OK
MENU_SETTLE = 0.8         # раскрытие выпадающего меню «Помощь»
POLL_INTERVAL = 0.4       # как часто опрашивать экран


@pytest.mark.astra
@pytest.mark.ui
# app: приложение остаётся открытым после теста, поэтому прогон идёт последним —
# иначе окно Altami перекрывает рабочий стол тестам, которые сверяют его с
# эталоном (сортировка — в tests/conftest.py).
@pytest.mark.app
class TestAstraMenuAbout(BaseVMTest):
    """Окно «О программе»: вкладка, целостность кнопки OK, закрытие по OK."""

    vm_id = "astra"

    async def _park_mouse(self) -> None:
        """Увести курсор в нейтральную точку, чтобы он не попал в кадр."""
        await self.qmp.mouse_move(*MOUSE_PARK)
        self._ptr = MOUSE_PARK
        await asyncio.sleep(0.3)

    async def _wait_region(self, name, box, want=True, timeout=10.0, shift=0):
        """Опрашивать область, пока она (не) совпадёт с эталоном.

        want=True  — ждём появления (SSIM > порога);
        want=False — ждём исчезновения (SSIM <= порога).
        Возвращает последний ComparisonResult (по нему видно, дождались ли).
        """
        loop = asyncio.get_event_loop()
        deadline = loop.time() + timeout
        result = None
        while loop.time() < deadline:
            await self._park_mouse()
            result = await self.compare_region(name, box, shift=shift)
            if result.passed == want:
                return result
            await asyncio.sleep(POLL_INTERVAL)
        return result

    async def _require_start_state(self) -> None:
        """Сверить экран со стартовым состоянием теста. Не совпало — падение.

        Стартовое состояние — конечное состояние TC-87: Altami Studio открыт,
        на экране главное окно с панелью инструментов. Тест ничего не нажимает
        до этой проверки и не пытается состояние подготовить: несовпадение —
        это сообщение, а не повод что-то открыть.
        """
        await self._park_mouse()
        toolbar = await self.compare_region("altami_app_toolbar", APP_TOOLBAR_BOX)
        if toolbar.passed:
            logger.info("Стартовое состояние подтверждено: Altami Studio открыт")
            return

        message = [
            "ВМ не в стартовом состоянии — тест не запускался.",
            "  Нужно: Altami Studio открыт, на экране главное окно "
            "(конечное состояние TC-87).",
            f"  Сейчас: панель инструментов не совпала с эталоном, "
            f"SSIM={toolbar.score:.6f} (нужно > {toolbar.threshold}).",
            f"    текущий: {toolbar.current_path}",
            f"    эталон:  {toolbar.baseline_path}",
        ]
        if toolbar.diff_path:
            message.append(f"    различия: {toolbar.diff_path}")
        message.append(
            "  Подготовьте состояние вручную (или прогоном TC-84 и TC-87) "
            "и запустите снова."
        )
        pytest.fail("\n".join(message))

    async def _check_ok_button(self) -> Optional[str]:
        """Проверить, что кнопка OK отрисована целиком.

        Возвращает текст проблемы или None, если кнопка в порядке. Падение
        отложено намеренно — см. docstring модуля: сначала надо дожать OK и
        закрыть окно, иначе модальное окно останется висеть поверх приложения.
        """
        crop_path = await self.capture_region("altami_about_ok_button", OK_BUTTON_BOX)
        left, top_y = OK_BUTTON_BOX[0], OK_BUTTON_BOX[1]
        with Image.open(crop_path) as crop:
            top, bottom = find_button_borders(crop)

        if top is None:
            return (
                "Кнопка OK не найдена в кадре: горизонтальной рамки нет в области "
                f"{OK_BUTTON_BOX}.\n"
                f"  кадр области: {crop_path}\n"
                "  Похоже, окно встало не на своё место или изменилась вёрстка — "
                "координаты области снимались на живой ВМ 10.08.2026."
            )

        if bottom is not None:
            height = bottom[0] - top[0] + 1
            logger.info(
                "Кнопка OK отрисована целиком: верх y=%d, низ y=%d, высота %d px",
                top[0] + top_y, bottom[0] + top_y, height,
            )
            return None

        return (
            "Кнопка OK обрезана: нижней рамки в кадре нет — её срезает нижний "
            "край окна «Altami Studio».\n"
            f"  верхняя рамка кнопки: y={top[0] + top_y}, "
            f"x={top[1] + left}..{top[2] + left}\n"
            f"  кадр области: {crop_path}\n"
            "  Это дефект вёрстки: в окно фиксированной высоты не помещается "
            "кнопка целиком. Так выглядит окно в демо-режиме и на Windows — "
            "см. docstring модуля."
        )

    async def test_about_dialog(self):
        """Помощь -> О программе: вкладка, целостность кнопки OK, закрытие."""
        # 0. Стартовое состояние TC-87: главное окно Altami Studio открыто.
        await self._require_start_state()

        # 1. Помощь -> «О программе».
        logger.info("Открываю Помощь -> О программе")
        await self.glide_click(*HELP_MENU)
        await asyncio.sleep(MENU_SETTLE)
        await self.glide_click(*ABOUT_ITEM)
        opened = await self._wait_region(
            "altami_about_title", ABOUT_TITLE_BOX, want=True,
            timeout=DIALOG_TIMEOUT, shift=DIALOG_SHIFT,
        )
        assert opened and opened.passed, (
            "Окно «Altami Studio» не открылось после «О программе»: "
            f"SSIM={opened.score:.6f}" if opened
            else "не удалось снять кадр после клика по «О программе»"
        )

        # 2. Открыта вкладка «О программе Altami Studio», а не «Плагины устройств».
        logger.info("Проверяю, что открыта вкладка «О программе Altami Studio»")
        await self._park_mouse()
        await self.assert_region(
            "altami_about_tabs", ABOUT_TABS_BOX, shift=DIALOG_SHIFT
        )

        # 3. Кнопка OK отрисована целиком. Падение отложено до шага 5.
        logger.info("Проверяю, что кнопка OK отображается целиком")
        ok_button_problem = await self._check_ok_button()

        # 4. Нажимаем OK — окно закрывается.
        logger.info("Нажимаю OK и жду закрытия окна")
        await self.glide_click(*OK_BUTTON)
        gone = await self._wait_region(
            "altami_about_title", ABOUT_TITLE_BOX, want=False,
            timeout=DISMISS_TIMEOUT, shift=DIALOG_SHIFT,
        )
        assert gone and not gone.passed, (
            "Окно «Altami Studio» не закрылось после OK: заголовок всё ещё "
            f"совпадает с эталоном (SSIM={gone.score:.6f})" if gone
            else "не удалось снять кадр после клика по OK"
        )

        # 5. Отложенный вердикт по кнопке: окно уже закрыто, состояние чистое.
        if ok_button_problem:
            pytest.fail(ok_button_problem)

        logger.info("Сценарий завершён — Altami Studio остаётся открытым")
