# --- Координаты кликов (пиксели гостя, режим 1920x1200) ----------------------
HELP_MENU = (514, 34)       # пункт «Помощь» в строке меню главного окна
ABOUT_ITEM = (552, 159)     # «О программе» — последний пункт меню «Помощь»
# Кнопка OK окна «О программе». Точка внутри ВИДИМОЙ части: кнопка сейчас
# обрезана снизу, и её нижняя половина недоступна для клика.
OK_BUTTON = (1083, 648)
MOUSE_PARK = (1750, 250)    # нейтральная точка: увести курсор из кадра

# --- Области для сравнения с эталоном (left, top, right, bottom) -------------
# Заголовок окна «Altami Studio»: значок и подпись. Доказывает, что окно
# открылось, и по нему же видно, что оно закрылось после OK.
ABOUT_TITLE_BOX = (781, 450, 890, 472)
# Обе вкладки целиком. Область захватывает и активную «О программе Altami
# Studio», и неактивную «Плагины устройств»: активная нарисована белой и
# приподнятой, неактивная — серой, поэтому эталон фиксирует не только надписи,
# но и то, КАКАЯ вкладка выбрана.
ABOUT_TABS_BOX = (784, 478, 1090, 514)
# Панель инструментов главного окна — по ней сверяется стартовое состояние.
APP_TOOLBAR_BOX = (0, 50, 1130, 85)

# --- Область разбора кнопки OK -----------------------------------------------
# Кроп для геометрической проверки: кнопка (её рамка сейчас на y=639, x от 1044
# до 1122) плюс запас вниз далеко за нижний край окна (y=656). Запас нужен,
# чтобы кнопка попадала в кадр и после исправления дефекта, когда окно станет
# выше и кнопка опустится. По горизонтали кроп не выходит за пределы окна: за
# его правым краем начинается холст приложения, а он тёмный и мешал бы разбору.
OK_BUTTON_BOX = (1035, 632, 1126, 706)

# --- Пороги разбора кадра ----------------------------------------------------
# Яркость (0-255), ниже которой пиксель считается «тёмным», то есть рамкой или
# текстом. Замеры на живой ВМ: рамка кнопки в фокусе (синяя) — 150, рамка без
# фокуса (серая) — 171, заливка кнопки — 236-253, фон окна — 240, холст
# приложения за окном — 120. Порог 200 разделяет их с большим запасом.
DARK_LUM = 200
# Минимальная длина горизонтального отрезка тёмных пикселей, чтобы считать его
# рамкой кнопки. Ширина кнопки — 78 px; буквы «OK» дают отрезки в 1-4 px.
MIN_BORDER_RUN = 40
# Отрезок длиной почти во весь кроп — это не рамка кнопки, а линия во всю
# ширину окна: край окна снизу или разделительная линия страницы вкладок.
# Кнопка (78 px) в кроп шириной 91 px укладывается с запасом, линия во всю
# ширину даёт 88-91 px, поэтому граница отсечения — «ширина кропа минус 8».
FULL_WIDTH_SLACK = 8
# Насколько нижняя рамка может разъехаться с верхней по краям, px.
SPAN_TOLERANCE = 3

# --- Таймауты опроса (секунды) -----------------------------------------------
DIALOG_TIMEOUT = 8.0      # появление окна «О программе» после клика по пункту
DISMISS_TIMEOUT = 6.0     # исчезновение окна после OK
MENU_SETTLE = 0.8         # раскрытие выпадающего меню «Помощь»
POLL_INTERVAL = 0.4       # как часто опрашивать экран


def _longest_dark_run(pixels, width: int, y: int) -> Tuple[int, int]:
    """Самый длинный отрезок тёмных пикселей в строке `y`: (длина, начало)."""
    best = best_start = current = start = 0
    for x in range(width):
        if pixels[x, y] < DARK_LUM:
            if current == 0:
                start = x
            current += 1
            if current > best:
                best, best_start = current, start
        else:
            current = 0
    return best, best_start


def find_button_borders(
    image: Image.Image,
) -> Tuple[Optional[Tuple[int, int, int]], Optional[Tuple[int, int, int]]]:
    """Найти в кадре верхнюю и нижнюю рамки кнопки: (y, x_левый, x_правый).

    Кнопка на этой теме — светлый прямоугольник с тонкой рамкой по контуру.
    В кадре она даёт две горизонтальные линии тёмных пикселей: верхнюю и
    нижнюю рамки. Если кнопку срезает край окна, нижней линии нет — по этому
    и отличается обрезанная кнопка от целой.

    Отбор строк идёт по двум признакам сразу, и оба нужны:

    * длина отрезка от MIN_BORDER_RUN до «ширина кропа минус FULL_WIDTH_SLACK».
      Снизу порог отсекает буквы «OK» (отрезки в единицы пикселей), сверху —
      линии во всю ширину окна: его нижний край и разделительную линию
      страницы вкладок. Ни та, ни другая к кнопке отношения не имеют;
    * у нижней рамки края совпадают с верхней (с допуском SPAN_TOLERANCE).
      Это второй заслон от посторонних линий: даже попади такая линия в
      разрешённую длину, её края с кнопкой не сойдутся.

    Возвращает (верхняя, нижняя); нижняя = None, если её в кадре нет.
    """
    grey = image.convert("L")
    width, height = grey.size
    pixels = grey.load()
    max_run = width - FULL_WIDTH_SLACK

    rows: List[Tuple[int, int, int]] = []
    for y in range(height):
        run, x0 = _longest_dark_run(pixels, width, y)
        if MIN_BORDER_RUN <= run <= max_run:
            rows.append((y, x0, x0 + run - 1))

    if not rows:
        return None, None

    top = rows[0]
    # Рамка бывает толщиной в 2 px, поэтому соседние строки пропускаем: иначе
    # вторая строка верхней рамки сошла бы за нижнюю.
    bottom = next(
        (row for row in rows
         if row[0] > top[0] + 2
         and abs(row[1] - top[1]) <= SPAN_TOLERANCE
         and abs(row[2] - top[2]) <= SPAN_TOLERANCE),
        None,
    )
    return top, bottom


@pytest.mark.windows
@pytest.mark.ui
# app: приложение остаётся открытым после теста, поэтому прогон идёт последним —
# иначе окно Altami перекрывает рабочий стол тестам, которые сверяют его с
# эталоном (сортировка — в tests/conftest.py).
@pytest.mark.app
class TestWindowsMenuAbout(BaseVMTest):
    """Окно «О программе»: вкладка, целостность кнопки OK, закрытие по OK."""

    vm_id = "windows"

    async def _park_mouse(self) -> None:
        """Увести курсор в нейтральную точку, чтобы он не попал в кадр."""
        await self.qmp.mouse_move(*MOUSE_PARK)
        self._ptr = MOUSE_PARK
        await asyncio.sleep(0.2)

    async def _wait_region(self, name, box, want=True, timeout=10.0):
        """Опрашивать область, пока она (не) совпадёт с эталоном.

        want=True  — ждём появления (SSIM > порога);
        want=False — ждём исчезновения (SSIM <= порога).
        Возвращает последний ComparisonResult (по нему видно, дождались ли).
        """
        loop = asyncio.get_event_loop()
        deadline = loop.time() + timeout
        result = None
        while loop.time() < deadline:
            await self._park_mouse()
            result = await self.compare_region(name, box)
            if result.passed == want:
                return result
            await asyncio.sleep(POLL_INTERVAL)
        return result

    async def _require_start_state(self) -> None:
        """Сверить экран со стартовым состоянием теста. Не совпало — падение.

        Стартовое состояние — конечное состояние TC-86: Altami Studio открыт,
        на экране главное окно с панелью инструментов. Тест ничего не нажимает
        до этой проверки и не пытается состояние подготовить: несовпадение —
        это сообщение, а не повод что-то открыть.
        """
        await self._park_mouse()
        toolbar = await self.compare_region("altami_app_toolbar", APP_TOOLBAR_BOX)
        if toolbar.passed:
            logger.info("Стартовое состояние подтверждено: Altami Studio открыт")
            return

        message = [
            "ВМ не в стартовом состоянии — тест не запускался.",
            "  Нужно: Altami Studio открыт, на экране главное окно "
            "(конечное состояние TC-86).",
            f"  Сейчас: панель инструментов не совпала с эталоном, "
            f"SSIM={toolbar.score:.6f} (нужно > {toolbar.threshold}).",
            f"    текущий: {toolbar.current_path}",
            f"    эталон:  {toolbar.baseline_path}",
        ]
        if toolbar.diff_path:
            message.append(f"    различия: {toolbar.diff_path}")
        message.append(
            "  Подготовьте состояние вручную (или прогоном TC-85 и TC-86) "
            "и запустите снова."
        )
        pytest.fail("\n".join(message))

    async def _check_ok_button(self) -> Optional[str]:
        """Проверить, что кнопка OK отрисована целиком.

        Возвращает текст проблемы или None, если кнопка в порядке. Падение
        отложено намеренно — см. docstring модуля: сначала надо дожать OK и
        закрыть окно, иначе модальное окно останется висеть поверх приложения.
        """
        crop_path = await self.capture_region("altami_about_ok_button", OK_BUTTON_BOX)
        left, top_y = OK_BUTTON_BOX[0], OK_BUTTON_BOX[1]
        with Image.open(crop_path) as crop:
            top, bottom = find_button_borders(crop)

        if top is None:
            return (
                "Кнопка OK не найдена в кадре: горизонтальной рамки нет в области "
                f"{OK_BUTTON_BOX}.\n"
                f"  кадр области: {crop_path}\n"
                "  Похоже, окно встало не на своё место или изменилась вёрстка — "
                "координаты области снимались на живой ВМ 10.08.2026."
            )

        if bottom is not None:
            height = bottom[0] - top[0] + 1
            logger.info(
                "Кнопка OK отрисована целиком: верх y=%d, низ y=%d, высота %d px",
                top[0] + top_y, bottom[0] + top_y, height,
            )
            return None

        return (
            "Кнопка OK обрезана: нижней рамки в кадре нет — её срезает нижний "
            "край окна «Altami Studio».\n"
            f"  верхняя рамка кнопки: y={top[0] + top_y}, "
            f"x={top[1] + left}..{top[2] + left}\n"
            f"  видно по вертикали: {OK_BUTTON_BOX[3] - (top[0] + top_y)} px "
            f"области ниже рамки, и ни одной строки нижней рамки\n"
            f"  кадр области: {crop_path}\n"
            "  Это дефект приложения: окно «О программе» ниже, чем нужно "
            "кнопке, и она не помещается целиком."
        )

    async def test_about_dialog(self):
        """Помощь -> О программе: вкладка, целостность кнопки OK, закрытие."""
        # 0. Стартовое состояние TC-86: главное окно Altami Studio открыто.
        await self._require_start_state()

        # 1. Помощь -> «О программе».
        logger.info("Открываю Помощь -> О программе")
        await self.glide_click(*HELP_MENU)
        await asyncio.sleep(MENU_SETTLE)
        await self.glide_click(*ABOUT_ITEM)
        opened = await self._wait_region(
            "altami_about_title", ABOUT_TITLE_BOX, want=True, timeout=DIALOG_TIMEOUT
        )
        assert opened and opened.passed, (
            "Окно «Altami Studio» не открылось после «О программе»: "
            f"SSIM={opened.score:.6f}" if opened
            else "не удалось снять кадр после клика по «О программе»"
        )

        # 2. Открыта вкладка «О программе Altami Studio», а не «Плагины устройств».
        logger.info("Проверяю, что открыта вкладка «О программе Altami Studio»")
        await self._park_mouse()
        await self.assert_region("altami_about_tabs", ABOUT_TABS_BOX)

        # 3. Кнопка OK отрисована целиком. Падение отложено до шага 5.
        logger.info("Проверяю, что кнопка OK отображается целиком")
        ok_button_problem = await self._check_ok_button()

        # 4. Нажимаем OK — окно закрывается.
        logger.info("Нажимаю OK и жду закрытия окна")
        await self.glide_click(*OK_BUTTON)
        gone = await self._wait_region(
            "altami_about_title", ABOUT_TITLE_BOX, want=False, timeout=DISMISS_TIMEOUT
        )
        assert gone and not gone.passed, (
            "Окно «Altami Studio» не закрылось после OK: заголовок всё ещё "
            f"совпадает с эталоном (SSIM={gone.score:.6f})" if gone
            else "не удалось снять кадр после клика по OK"
        )

        # 5. Отложенный вердикт по кнопке: окно уже закрыто, состояние чистое.
        if ok_button_problem:
            pytest.fail(ok_button_problem)

        logger.info("Сценарий завершён — Altami Studio остаётся открытым")
