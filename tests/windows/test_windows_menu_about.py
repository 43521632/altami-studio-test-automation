"""UI-тест окна «О программе» Altami Studio на Windows.

Стартовое состояние — конечное состояние TC-86: приложение уже запущено,
лицензия активирована, на экране главное окно. Состояние тест НЕ готовит:
первым шагом он сверяет экран с эталоном стартового состояния и при
расхождении падает, ничего не нажимая (то же правило, что в TC-86).

Сценарий:

1. Помощь -> «О программе»: открывается окно «Altami Studio».
2. Проверяем, что открыта вкладка «О программе Altami Studio» (а не соседняя
   «Плагины устройств»).
3. Проверяем, что кнопка OK отрисована ЦЕЛИКОМ и не обрезана нижним краем
   окна. Это геометрическая проверка, а не сравнение с эталоном, — почему
   именно так, см. ниже.
4. Нажимаем OK — окно закрывается, тест завершён.

Приложение НАМЕРЕННО остаётся открытым в конце — как в TC-85 и TC-86: на нём
строятся следующие сценарии.

Имя файла и порядок в прогоне. Тесты с маркером `app` идут в конце прогона, а
между собой — в порядке сбора, то есть по алфавиту имён файлов (сортировка в
tests/conftest.py стабильна). «menu_about» стоит после «license_activation»,
поэтому цепочка складывается правильно: запуск (TC-85) -> активация лицензии
(TC-86) -> это окно. Переименование файла порядок сломает.

ПРОВЕРКА КНОПКИ OK — ПОЧЕМУ НЕ ЭТАЛОН. Сравнение с эталоном отвечает на
вопрос «выглядит ли как раньше», а не «отрисовано ли целиком»: эталон
снимается с живой машины, и если кнопка обрезана уже сейчас, то дефект просто
попадёт в эталон и тест будет вечно зелёным. Поэтому кнопка проверяется
геометрически, по самому кадру: у целой кнопки есть верхняя И нижняя рамка,
у обрезанной — только верхняя, потому что нижнюю срезает край окна. Разбор
кадра — в `find_button_borders` ниже.

НА МОМЕНТ НАПИСАНИЯ ТЕСТ ПАДАЕТ, И ЭТО ВЕРНО. На живой ВМ 10.08.2026
(Altami Studio 4.1.0 d808645) кнопка OK обрезана: её верхняя рамка на y=639,
клиентская область окна кончается на y=656, нижней рамки нет — видно 18 px
кнопки вместо ~27. Это дефект приложения, и тест о нём сообщает.

Падение по кнопке ОТЛОЖЕНО до конца сценария. Тест сначала дожимает OK и
убеждается, что окно закрылось, и только потом падает. Иначе каждый прогон
оставлял бы поверх приложения открытое модальное окно, а оно перехватывает
клики — следующий тест цепочки (и следующий прогон этого же теста) падал бы
уже по непонятной причине. Остальные проверки падают сразу, как обычно: они
означают неожиданное расхождение, с которым всё равно нужно разбираться
руками.

ЭТАЛОНЫ СНИМАТЬ ТОЛЬКО С УСТОЯВШЕГОСЯ ОКНА. Окно «О программе» появляется с
проявлением: первые доли секунды оно полупрозрачно, и фон заголовка идёт 229
вместо 243. Если эталона нет, он создаётся из первого же снятого кадра
(правило бутстрапа, см. screenshot_compare) — и цикл ожидания в `_wait_region`
успевает поймать окно именно полупрозрачным. Такой эталон потом не совпадает
ни с одним нормальным кадром: SSIM 0.14. Поэтому, если эталоны удалили,
создавать их надо с ЗАВЕДОМО устоявшегося кадра — открыть окно руками, выждать
пару секунд и вырезать области. С правильным эталоном цикл ожидания сам
дожидается полной непрозрачности, и отдельная пауза тесту не нужна.

Позиция окна стабильна: 6 открытий подряд на живой ВМ 10.08.2026 дали ровно
одни и те же границы (верх y=447, низ y=656), поэтому допуск на смещение
(shift=) здесь не нужен — в отличие от тестов Astra, где окна разъезжаются.

Координаты и области сняты на живой ВМ 10.08.2026 в видеорежиме 1920x1200.
"""

