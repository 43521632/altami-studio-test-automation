"""Разбор геометрии виджета по кадру: отрисован ли он целиком.

Сравнение с эталоном отвечает на вопрос «выглядит ли как раньше», а не
«отрисовано ли целиком»: эталон снимается с живой машины, поэтому уже
имеющийся дефект вёрстки просто попадёт в эталон и тест будет вечно зелёным.
Здесь другой подход — кадр разбирается сам по себе, безотносительно эталона.

Пока модуль умеет одно: находить рамки кнопки, см. :func:`find_button_borders`.
Им пользуются тесты окна «О программе» на Windows и Astra — стиль кнопок у
систем разный, а признак один и тот же, поэтому и пороги общие.
"""

import logging
from typing import List, Optional, Tuple

logger = logging.getLogger(__name__)

#: Яркость (0-255), ниже которой пиксель считается «тёмным», то есть рамкой
#: или текстом. Замеры на живых ВМ: рамка кнопки в фокусе на Windows — 150,
#: на Astra — 95, рамка без фокуса — 171, заливка кнопки — 236-253, фон окна —
#: 239-240, холст приложения за окном — 120. Порог 200 разделяет их с запасом.
DARK_LUM = 200

#: Минимальная длина горизонтального отрезка тёмных пикселей, чтобы считать его
#: рамкой кнопки. Ширина кнопки OK — 78 px на обеих системах; буквы «OK» дают
#: отрезки в 1-4 px.
MIN_BORDER_RUN = 40

#: Отрезок длиной почти во весь кроп — это не рамка кнопки, а линия во всю
#: ширину окна: нижний край окна или разделительная линия страницы вкладок.
#: Граница отсечения — «ширина кропа минус это число».
FULL_WIDTH_SLACK = 8

#: Насколько нижняя рамка может разъехаться с верхней по краям, px.
SPAN_TOLERANCE = 3

#: Рамка бывает толщиной в 2 px: соседние строки при поиске нижней пропускаем,
#: иначе вторая строка верхней рамки сошла бы за нижнюю.
MIN_BORDER_GAP = 2

#: Найденная рамка: (строка, левый край, правый край) в координатах кропа.
Border = Tuple[int, int, int]


def _longest_dark_run(pixels, width: int, y: int) -> Tuple[int, int]:
    """Самый длинный отрезок тёмных пикселей в строке `y`: (длина, начало)."""
    best = best_start = current = start = 0
    for x in range(width):
        if pixels[x, y] < DARK_LUM:
            if current == 0:
                start = x
            current += 1
            if current > best:
                best, best_start = current, start
        else:
            current = 0
    return best, best_start


def find_button_borders(image) -> Tuple[Optional[Border], Optional[Border]]:
    """Найти в кадре верхнюю и нижнюю рамки кнопки.

    Кнопка — светлый прямоугольник с тонкой рамкой по контуру, поэтому в кадре
    она даёт две горизонтальные линии тёмных пикселей: верхнюю и нижнюю рамки.
    Если кнопку срезает край окна, нижней линии нет — по этому и отличается
    обрезанная кнопка от целой.

    Отбор строк идёт по двум признакам сразу, и оба нужны:

    * длина отрезка от :data:`MIN_BORDER_RUN` до «ширина кропа минус
      :data:`FULL_WIDTH_SLACK`». Снизу порог отсекает буквы на кнопке (отрезки
      в единицы пикселей), сверху — линии во всю ширину окна: его нижний край
      и разделительную линию страницы вкладок. Ни та, ни другая к кнопке
      отношения не имеют;
    * у нижней рамки края совпадают с верхней (допуск :data:`SPAN_TOLERANCE`).
      Это второй заслон от посторонних линий: даже попади такая линия в
      разрешённую длину, её края с кнопкой не сойдутся.

    Args:
        image: кроп кадра (PIL Image) — область кнопки с запасом вниз, не
            выходящая за пределы окна по горизонтали.

    Returns:
        Пару (верхняя рамка, нижняя рамка). Нижняя — None, если её в кадре
        нет, то есть кнопка обрезана. Обе None, если кнопки в кадре не нашлось.
    """
    grey = image.convert("L")
    width, height = grey.size
    pixels = grey.load()
    max_run = width - FULL_WIDTH_SLACK

    rows: List[Border] = []
    for y in range(height):
        run, x0 = _longest_dark_run(pixels, width, y)
        if MIN_BORDER_RUN <= run <= max_run:
            rows.append((y, x0, x0 + run - 1))

    if not rows:
        return None, None

    top = rows[0]
    bottom = next(
        (row for row in rows
         if row[0] > top[0] + MIN_BORDER_GAP
         and abs(row[1] - top[1]) <= SPAN_TOLERANCE
         and abs(row[2] - top[2]) <= SPAN_TOLERANCE),
        None,
    )
    return top, bottom
